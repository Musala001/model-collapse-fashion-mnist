"""Generate a Kaggle script kernel from src/mc and a config.

    python tools/build_kernel.py configs/smoke.json
writes kernels/<slug>/run.py and kernels/<slug>/kernel-metadata.json.
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
USER = "musalandouvhada"

TEMPLATE = '''# AUTO-GENERATED by tools/build_kernel.py from src/mc. Do not edit by hand.
import os, subprocess, sys
subprocess.run(["nvidia-smi", "-L"])
subprocess.run([sys.executable, "-m", "pip", "install", "-q", "lpips", "pytorch-fid"], check=True)
SRC = {src!r}
CFG = {cfg!r}
code_dir = "/tmp/mc_code/mc"
os.makedirs(code_dir, exist_ok=True)
for name, text in SRC.items():
    with open(os.path.join(code_dir, name), "w") as f:
        f.write(text)
sys.path.insert(0, "/tmp/mc_code")
# outputs from an earlier kernel attached as a data source are resumed from
if CFG.get("resume_slug"):
    import glob
    hits = sorted(glob.glob("/kaggle/input/**/" + CFG["resume_slug"] + "/out", recursive=True))
    print("[resume] candidates", hits, flush=True)
    if not hits:
        raise SystemExit("[resume] attached output not found under /kaggle/input")
    CFG["resume_dir"] = hits[0]
from mc.run import main
main(CFG, "/kaggle/working/out")
'''


def build(cfg_path):
    cfg = json.load(open(cfg_path))
    slug = cfg["slug"]
    src_dir = os.path.join(ROOT, "src", "mc")
    src = {f: open(os.path.join(src_dir, f)).read()
           for f in sorted(os.listdir(src_dir)) if f.endswith(".py")}
    kdir = os.path.join(ROOT, "kernels", slug)
    os.makedirs(kdir, exist_ok=True)
    with open(os.path.join(kdir, "run.py"), "w") as f:
        f.write(TEMPLATE.format(src=src, cfg=cfg))
    meta = {
        "id": f"{USER}/{slug}",
        "title": slug,
        "code_file": "run.py",
        "language": "python",
        "kernel_type": "script",
        "is_private": True,
        "enable_gpu": True,
        "enable_internet": True,
        "dataset_sources": [],
        "competition_sources": [],
        "kernel_sources": [f"{USER}/{cfg['resume_slug']}"] if cfg.get("resume_slug") else [],
    }
    with open(os.path.join(kdir, "kernel-metadata.json"), "w") as f:
        json.dump(meta, f, indent=1)
    print(kdir)


if __name__ == "__main__":
    build(sys.argv[1])
